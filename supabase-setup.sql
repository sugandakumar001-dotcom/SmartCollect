-- SmartCollect Supabase setup
-- Run this whole script in Supabase Dashboard > SQL Editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'User',
  role text not null check (role in ('admin','driver')),
  vehicle_id text,
  created_at timestamptz not null default now()
);
create table if not exists public.vehicles (
  vehicle_code text primary key,
  driver_name text,
  route_name text,
  status text not null default 'Available',
  created_at timestamptz not null default now()
);
create table if not exists public.vehicle_locations (
  vehicle_id text primary key references public.vehicles(vehicle_code) on delete cascade,
  latitude double precision not null check(latitude between -90 and 90),
  longitude double precision not null check(longitude between -180 and 180),
  accuracy_m double precision,
  recorded_at timestamptz not null default now()
);
create table if not exists public.waste_bins (
  id bigint generated by default as identity primary key,
  bin_code text unique not null,
  waste_type text not null,
  fill_level integer not null default 0 check(fill_level between 0 and 100),
  status text not null default 'Normal',
  created_at timestamptz not null default now()
);
create table if not exists public.pickup_requests (
  id bigint generated by default as identity primary key,
  request_code text unique not null,
  waste_type text not null,
  status text not null default 'Pending',
  created_at timestamptz not null default now()
);
create table if not exists public.citizens (
  id bigint generated by default as identity primary key,
  full_name text not null,
  area text,
  phone text,
  created_at timestamptz not null default now()
);
create or replace function public.current_role()
returns text language sql stable security definer set search_path=public
as $$ select role from public.profiles where id=auth.uid() $$;
create or replace function public.current_vehicle_id()
returns text language sql stable security definer set search_path=public
as $$ select vehicle_id from public.profiles where id=auth.uid() $$;
alter table public.profiles enable row level security;
alter table public.vehicles enable row level security;
alter table public.vehicle_locations enable row level security;
alter table public.waste_bins enable row level security;
alter table public.pickup_requests enable row level security;
alter table public.citizens enable row level security;
drop policy if exists "profile self or admin read" on public.profiles;
create policy "profile self or admin read" on public.profiles for select to authenticated
using (id=auth.uid() or public.current_role()='admin');
drop policy if exists "admin manages profiles" on public.profiles;
create policy "admin manages profiles" on public.profiles for all to authenticated
using (public.current_role()='admin') with check (public.current_role()='admin');
drop policy if exists "authenticated reads vehicles" on public.vehicles;
create policy "authenticated reads vehicles" on public.vehicles for select to authenticated using (true);
drop policy if exists "admin manages vehicles" on public.vehicles;
create policy "admin manages vehicles" on public.vehicles for all to authenticated
using (public.current_role()='admin') with check (public.current_role()='admin');
drop policy if exists "driver updates assigned vehicle status" on public.vehicles;
create policy "driver updates assigned vehicle status" on public.vehicles for update to authenticated
using (public.current_role()='driver' and vehicle_code=public.current_vehicle_id())
with check (public.current_role()='driver' and vehicle_code=public.current_vehicle_id());
drop policy if exists "admin or assigned driver reads locations" on public.vehicle_locations;
create policy "admin or assigned driver reads locations" on public.vehicle_locations for select to authenticated
using (public.current_role()='admin' or vehicle_id=public.current_vehicle_id());
drop policy if exists "assigned driver writes own location" on public.vehicle_locations;
create policy "assigned driver writes own location" on public.vehicle_locations for insert to authenticated
with check (public.current_role()='driver' and vehicle_id=public.current_vehicle_id());
drop policy if exists "assigned driver updates own location" on public.vehicle_locations;
create policy "assigned driver updates own location" on public.vehicle_locations for update to authenticated
using (public.current_role()='driver' and vehicle_id=public.current_vehicle_id())
with check (public.current_role()='driver' and vehicle_id=public.current_vehicle_id());
drop policy if exists "admin manages bins" on public.waste_bins;
create policy "admin manages bins" on public.waste_bins for all to authenticated
using (public.current_role()='admin') with check (public.current_role()='admin');
drop policy if exists "admin manages requests" on public.pickup_requests;
create policy "admin manages requests" on public.pickup_requests for all to authenticated
using (public.current_role()='admin') with check (public.current_role()='admin');
drop policy if exists "admin manages citizens" on public.citizens;
create policy "admin manages citizens" on public.citizens for all to authenticated
using (public.current_role()='admin') with check (public.current_role()='admin');
-- Enable Realtime for vehicle location changes.
do $$ begin
  alter publication supabase_realtime add table public.vehicle_locations;
exception when duplicate_object then null;
when undefined_object then null;
end $$;
